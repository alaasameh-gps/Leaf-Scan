export type ConditionType =
  | "healthy"
  | "fungal"
  | "bacterial"
  | "viral"
  | "oomycete"
  | "pest"
  | "background"
  | "unknown";

export interface PlantClassInfo {
  /** Dataset folder name, used as the label id returned by the model. */
  id: string;
  cropEn: string | null;
  cropAr: string | null;
  /** Binomial used to query GBIF. Null when the label is not a crop. */
  scientificName: string | null;
  /** Used when the binomial lookup fails (datasets labels stay generic). */
  fallbackGenus: string | null;
  conditionEn: string | null;
  conditionAr: string | null;
  conditionType: ConditionType;
  /** Wikipedia search term used to retrieve a sourced article at runtime. */
  diseaseSearchTerm: string | null;
  isBackground: boolean;
}

